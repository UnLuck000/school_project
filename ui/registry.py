HANDLERS: dict[str, Callable[[object], None]] = {}


def implements(button_id: str):
    """Декоратор: привязывает функцию handler(window) к кнопке из FEATURES."""
    def decorator(func: Callable[[object], None]):
        HANDLERS[button_id] = func
        return func
    return decorator